export const CHAR_W = 6; // 5px glyph + 1px spacing
export const LINE_H = 8;

const cache: Record<number, Record<string, HTMLCanvasElement>> = {};

function glyphCanvas(ch: string, colorIndex: number): HTMLCanvasElement | null {
  const def = GLYPHS[ch];
  if (!def) return null;
  const byColor = (cache[colorIndex] ||= {});
  let c = byColor[ch];
  if (!c) {
    c = document.createElement('canvas');
    c.width = 5;
    c.height = 7;
    const ctx = c.getContext('2d')!;
    ctx.fillStyle = PALETTE[colorIndex];
    const rows = def.split('|');
    for (let y = 0; y < 7; y++) {
      for (let x = 0; x < 5; x++) {
        if (rows[y][x] === '#') ctx.fillRect(x, y, 1, 1);
      }
    }
    byColor[ch] = c;
  }
  return c;
}

export function drawText(
  ctx: CanvasRenderingContext2D,
  text: string,
  x: number,
  y: number,
  colorIndex = 3,
): void {
  let cx = x;
  for (const ch of text) {
    if (ch !== ' ') {
      const g = glyphCanvas(ch, colorIndex);
      if (g) ctx.drawImage(g, cx, y);
    }
    cx += CHAR_W;
  }
}

export function textWidth(text: string): number {
  return [...text].length * CHAR_W;
}
