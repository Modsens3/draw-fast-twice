export interface CharSprites {
  // [dir][frame]: frame 0 = stand, 1 = stride A, 2 = stride B (mirror)
  down: HTMLCanvasElement[];
  up: HTMLCanvasElement[];
  left: HTMLCanvasElement[];
  right: HTMLCanvasElement[];
}

export type SpriteId = 'player' | 'villager' | 'professor' | 'rival';

function buildChar(
  downStand: string[],
  downWalk: string[],
  upStand: string[],
  upWalk: string[],
  sideStand: string[],
  sideWalk: string[],
): CharSprites {
  const dS = artToCanvas(downStand);
  const dW = artToCanvas(downWalk);
  const uS = artToCanvas(upStand);
  const uW = artToCanvas(upWalk);
  const rS = artToCanvas(sideStand);
  const rW = artToCanvas(sideWalk);
  return {
    down: [dS, dW, flipCanvasH(dW)],
    up: [uS, uW, flipCanvasH(uW)],
    right: [rS, rW, rW],
    left: [flipCanvasH(rS), flipCanvasH(rW), flipCanvasH(rW)],
  };
}

let sprites: Record<SpriteId, CharSprites> | null = null;

export function charSprites(id: SpriteId): CharSprites {
  if (!sprites) {
    sprites = {
      player: buildChar(
        PLAYER_DOWN_STAND,
        PLAYER_DOWN_WALK,
        PLAYER_UP_STAND,
        PLAYER_UP_WALK,
        PLAYER_SIDE_STAND,
        PLAYER_SIDE_WALK,
      ),
      villager: buildChar(
        VILLAGER_DOWN,
        VILLAGER_DOWN,
        VILLAGER_UP,
        VILLAGER_UP,
        VILLAGER_SIDE,
        VILLAGER_SIDE,
      ),
      professor: buildChar(
        PROFESSOR_DOWN,
        PROFESSOR_DOWN,
        PROFESSOR_UP,
        PROFESSOR_UP,
        PROFESSOR_SIDE,
        PROFESSOR_SIDE,
      ),
      rival: buildChar(RIVAL_DOWN, RIVAL_DOWN, RIVAL_UP, RIVAL_UP, RIVAL_SIDE, RIVAL_SIDE),
    };
  }
  return sprites[id];
}

