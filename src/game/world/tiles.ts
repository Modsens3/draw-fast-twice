let atlas: Record<TileId, HTMLCanvasElement> | null = null;

export function tileCanvas(id: TileId): HTMLCanvasElement {
  if (!atlas) {
    atlas = {} as Record<TileId, HTMLCanvasElement>;
    for (const key of Object.keys(T) as TileId[]) {
      atlas[key] = artToCanvas(T[key].art);
    }
  }
  return atlas[id];
}

export function tileBehavior(id: TileId): TileBehavior {
  return T[id].behavior;
}
