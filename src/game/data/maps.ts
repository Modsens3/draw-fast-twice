let registry: Map<string, GameMap> | null = null;

export function getMap(id: string): GameMap {
  if (!registry) {
    registry = new Map(DEFS.map((d) => [d.id, new GameMap(d)]));
  }
  const m = registry.get(id);
  if (!m) throw new Error(`Unknown map: ${id}`);
  return m;
}

